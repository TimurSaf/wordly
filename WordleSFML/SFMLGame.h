#ifndef SFMLGAME_H
#define SFMLGAME_H

/**
 * \file
 * \brief Заголовочный файл с классом SFMLGame для управления основным игровым циклом.
 *
 * Данный файл содержит объявление класса SFMLGame, который отвечает
 * за инициализацию оконного контекста SFML и запуск игрового цикла.
 */

#include <SFML/Graphics.hpp>
#include "Game.h"

/**
 * \class SFMLGame
 * \brief Класс, управляющий окном SFML и игровым циклом.
 *
 * Класс SFMLGame инициализирует окно для игры, загружает шрифт,
 * запускает и контролирует основной игровой цикл до завершения.
 */
class SFMLGame
{
public:
    /**
     * \brief Конструктор класса SFMLGame.
     *
     * Инициализирует окно SFML, загружает шрифт и подготавливает объект Game
     * для запуска игрового цикла.
     * 
     */
    SFMLGame();

    /**
     * \brief Деструктор класса SFMLGame.
     */
    virtual ~SFMLGame() = default;

    /**
     * \brief Запускает основной игровой цикл.
     *
     * В безусловном цикле обрабатывает события окна, обновляет состояние игры
     * и выполняет отрисовку до тех пор, пока окно не будет закрыто.
     *
     * \return void
     */
    void gameLoop();

private:
    sf::RenderWindow _window;    /**< Окно SFML, в котором выполняется игра. */
    sf::Font         _font;      /**< Шрифт, используемый во всех текстовых элементах игры. */
    Game             _game;      /**< Объект Game, управляющий логикой и интерфейсами внутри игры. */

    /**
     * \brief Загружает и возвращает шрифт для использования в игре.
     *
     * Выполняет загрузку файла шрифта из заранее известного пути и
     * возвращает объект sf::Font. В случае неудачи бросает исключение.
     *
     * \return sf::Font Загрузка шрифта, готового к использованию.
     * \throw std::runtime_error Если не удалось загрузить файл шрифта.
     */
    static sf::Font loadFont();
};

#endif // SFMLGAME_H
